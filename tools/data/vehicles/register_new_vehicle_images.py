"""Encode reviewed transparent images and register all 23 new model families."""
import hashlib
import json
import html
from pathlib import Path
from PIL import Image
from build_recommendation_images import image_style
from build_new_vehicle_assets import DATA, ROOT, save

PAGE = ROOT / 'front/src/features/vehicle'
PUBLIC = ROOT / 'front/public'
TARGET = PUBLIC / 'images/recommendations/new-models-20261028'


def main():
    sources = {}
    for file in ['image-downloads.json', 'remaining-image-downloads.json', 'alternative-image-downloads.json', 'z4-press-download.json']:
        for row in json.loads((DATA/file).read_text(encoding='utf-8')):
            sources[row['slug']] = row
    selected = {
        'BMW::2시리즈 쿠페': 'bmw-2-coupe', 'BMW::2시리즈 그란쿠페': 'bmw-2-gran-coupe',
        'BMW::4시리즈 쿠페': 'bmw-4-coupe', 'BMW::4시리즈 그란쿠페': 'bmw-4-gran-coupe',
        'BMW::4시리즈 컨버터블': 'bmw-4-convertible', 'BMW::8시리즈 그란쿠페': 'bmw-8-gran-coupe', 'BMW::Z4': 'bmw-z4',
        'MINI::Cooper Convertible': 'mini-convertible', '토요타::GR86': 'toyota-gr86',
        '마세라티::GranTurismo': 'maserati-granturismo', '마세라티::GranCabrio': 'maserati-grancabrio',
        'Porsche::911 쿠페': 'porsche-911-coupe-full', 'Porsche::911 카브리올레': 'porsche-911-cabriolet-full', 'Porsche::911 타르가': 'porsche-911-targa-full',
        **{'Ferrari::'+model:slug for model,slug in [('296 GTB','ferrari-296-gtb'),('296 GTS','ferrari-296-gts'),('12Cilindri','ferrari-12-cilindri'),('12Cilindri Spider','ferrari-12-cilindri-spider'),('Amalfi','ferrari-amalfi'),('Amalfi Spider','ferrari-amalfi-spider'),('Roma Spider','ferrari-roma-spider')]},
        'Lamborghini::Temerario':'lamborghini-temerario', 'Lamborghini::Revuelto':'lamborghini-revuelto',
    }
    # Browser image captures preserve the public, successfully rendered source.
    for slug in ['mini-convertible', 'maserati-granturismo', 'maserati-grancabrio']:
        original = next(r for r in json.loads((DATA/'remaining-image-downloads.json').read_text(encoding='utf-8')) if r['slug']==slug)
        sources[slug] = {**original, 'file':str((DATA/'images'/f'{slug}-browser.png').relative_to(ROOT)).replace('\\','/'), 'capture':'browser-rendered-official-image'}
    sources['bmw-z4'] = sources['bmw-z4-press']
    TARGET.mkdir(parents=True,exist_ok=True)
    registry, manifest = {}, []
    for identity, slug in selected.items():
        source = sources[slug]
        original = ROOT / source['file']
        edited = DATA / 'cutouts' / f'{slug}.png'
        chosen = edited if edited.exists() else original
        destination = TARGET / f'{slug}.webp'
        with Image.open(chosen) as image:
            image.convert('RGBA').save(destination,'WEBP',lossless=True,exact=True,method=6)
        style, dimensions = image_style(destination)
        brand,model = identity.split('::',1)
        angle = '전면' if slug.startswith('porsche') else '전면 사선'
        info = {'src':'/'+destination.relative_to(PUBLIC).as_posix(), 'alt':f'{brand} {model} {angle} 대표 이미지', 'style':style}
        registry[identity] = info
        manifest.append({'brand':brand,'model':model,'slug':slug,**info,**dimensions,
            'source_page':source['source_url'],'source_image_url':source['image_url'],
            'source_file':original.relative_to(ROOT).as_posix(), 'source_sha256':hashlib.sha256(original.read_bytes()).hexdigest(),
            'sha256':hashlib.sha256(destination.read_bytes()).hexdigest(),
            'processing':'imagegen-background-extraction' if edited.exists() else 'native-transparent-format-conversion',
            'capture':source.get('capture','original-file-download'),
            'note':'모델군 대표 사진입니다. 색상·휠·M/JCW/GT3 등 세부 트림 장비가 다를 수 있습니다.'})
    catalog = json.loads((ROOT/'data/households/synthetic/lifestyle-million-20261028/catalog.json').read_text(encoding='utf-8'))
    expected = {v['brand']+'::'+v['model'] for v in catalog if v['id'].startswith(('SPORT-','research-'))}
    if expected != set(registry):
        raise ValueError(f'Missing/extra images: {expected ^ set(registry)}')
    (PAGE/'newVehicleImages.js').write_text('// Generated by tools/data/vehicles/register_new_vehicle_images.py.\n// Representative models; trim equipment may differ.\nexport const newVehicleImages = '+json.dumps(registry,ensure_ascii=False,indent=2)+';\n',encoding='utf-8')
    save('image-manifest.json',manifest)
    cards = []
    for row in manifest:
        style = ';'.join(f"{'max-width' if key == 'maxWidth' else key}:{value}" for key,value in row['style'].items())
        cards.append(f'<article><div class="image"><img alt="{html.escape(row["model"])}" src="../../../../front/public{row["src"]}" style="{style}"></div><h2>{html.escape(row["brand"]+" "+row["model"])}</h2></article>')
    page = '''<!doctype html><html lang="ko"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>신규 차량 사진 검수</title>
<style>body{font:14px sans-serif;background:#f7f8fb;color:#203960;margin:32px}main{display:grid;grid-template-columns:repeat(4,minmax(0,1fr));gap:16px}article{background:white;border:1px solid #e2e8f0;border-radius:16px;padding:16px}.image{position:relative;aspect-ratio:1.5;overflow:hidden}h2{font-size:16px}@media(max-width:768px){main{grid-template-columns:repeat(2,minmax(0,1fr))}body{margin:16px}}</style>
<h1>신규 차량 23개 모델군 · 대표 사진</h1><p>공식 원본 기반 · 세부 트림과 색상은 다를 수 있습니다.</p><main>'''
    (DATA/'image-review.html').write_text(page+''.join(cards)+'</main></html>',encoding='utf-8')
    print(json.dumps({'models':len(manifest),'transparent_images':len(manifest),'bytes':sum((PUBLIC/r['src'].lstrip('/')).stat().st_size for r in manifest)}))


if __name__ == '__main__':
    main()
