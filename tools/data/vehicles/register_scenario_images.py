"""Register official representative photos for the active scenario catalog."""
import concurrent.futures
import hashlib
import io
import json
from pathlib import Path
import urllib.parse
import urllib.request

from PIL import Image

ROOT = Path(__file__).resolve().parents[3]
DATA = ROOT / 'data/vehicles/scenario-images-20261030'
PUBLIC = ROOT / 'front/public'
TARGET = PUBLIC / 'images/recommendations/scenario-models-20261030'


def download(row):
    url = urllib.parse.quote(row['image_url'], safe=':/?=&%,-._')
    request = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0'})
    raw = urllib.request.urlopen(request, timeout=25).read()
    with Image.open(io.BytesIO(raw)) as original:
        image = original.convert('RGBA')
        image.thumbnail((1200, 900), Image.Resampling.LANCZOS)
        path = TARGET / f"{row['slug']}.webp"
        image.save(path, 'WEBP', quality=90, method=6)
        dimensions = image.size
    return {**row, 'src': '/' + path.relative_to(PUBLIC).as_posix(),
            'alt': f"{row['brand']} {row['model']} 대표 이미지",
            'width': dimensions[0], 'height': dimensions[1],
            'source_sha256': hashlib.sha256(raw).hexdigest(),
            'sha256': hashlib.sha256(path.read_bytes()).hexdigest(),
            'checked_on': '2026-10-30', 'processing': 'aspect-preserving-webp-conversion'}


def build():
    rows = json.loads((DATA / 'sources.json').read_text(encoding='utf-8'))
    TARGET.mkdir(parents=True, exist_ok=True)
    completed, errors = [], []
    with concurrent.futures.ThreadPoolExecutor(max_workers=6) as pool:
        jobs = {pool.submit(download, row): row for row in rows}
        for future in concurrent.futures.as_completed(jobs):
            try:
                completed.append(future.result())
            except Exception as error:
                errors.append({'slug': jobs[future]['slug'], 'error': str(error)})
    completed.sort(key=lambda row: row['slug'])
    (DATA / 'manifest.json').write_text(json.dumps(completed, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    if errors:
        raise RuntimeError(json.dumps(errors, ensure_ascii=False))
    registry = {f"{row['brand']}::{row['model']}": {key: row[key] for key in ('src', 'alt')} for row in completed}
    (ROOT / 'front/src/features/vehicle/scenarioModelImages.js').write_text(
        '// Generated by tools/data/vehicles/register_scenario_images.py.\n'
        'export const scenarioModelImages = ' + json.dumps(registry, ensure_ascii=False, indent=2) + ';\n', encoding='utf-8')
    print(f'Registered {len(completed)} model photos')


if __name__ == '__main__':
    build()
